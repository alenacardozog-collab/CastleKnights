#!/usr/bin/env node
'use strict';
/* Packs the animations of the character pack that the game did not use yet into js/chars_extra_assets.js
   (data URIs, so they load from file:// too), plus how many frames each one has (window.CK_ANIMS_EXTRA).
   Source: the downloaded pack in assets/characters/nuevos/ and the Minifolks villagers in assets/npc/, which stay
   on this PC (.gitignore); only the generated file goes to the repository.
   js/chars_assets.js (pack_chars.py) is not touched: its source folders no longer exist on disk.
   Run:  node tools/pack/pack_extra.js     (or: npm run build:extra) */
const fs = require('fs'), path = require('path');
const { framesPerRow } = require('./png_frames.js');
const ROOT = path.join(__dirname, '..', '..');
const PACK = path.join(ROOT, 'assets/characters/nuevos/Characters/Characters(100x100 split)');
const NPC = path.join(ROOT, 'assets/npc/MinifolksVillagers/Outline');

// pack folder -> game id, and which of its sheets the game still lacks (pack name -> game animation)
// not every guard has all of them (the axeman and the lancer do not block, the archer has two attacks): '?' = optional
const GUARD = { Attack01: 'attack1', Attack02: 'attack2', 'Attack03?': 'attack3', 'Block?': 'block', Hurt: 'hurt', Death: 'death', 'Walk02?': 'walk2' };
const CHARS = {
  // castle guards (they only had idle and walk)
  'Knight': ['g_knight', GUARD],
  'Knight Templar': ['g_templar', GUARD],
  'Lancer': ['g_lancer', GUARD],
  'Armored Axeman': ['g_axeman', GUARD],
  'Archer': ['g_archer', GUARD],
  'Priest': ['g_priest', { Attack: 'attack1', Heal: 'heal', Hurt: 'hurt', Death: 'death' }],
  // enemies: the attacks, blocks and summons that were left out
  'Bat': ['bat', { Attack02: 'attack2' }],
  'Armored Orc': ['orc_armored', { Attack02: 'attack2', Attack03: 'attack3', Block: 'block' }],
  'Elite Orc': ['orc_elite', { Attack02: 'attack2', Attack03: 'attack3' }],
  'Skeleton': ['skeleton', { Attack02: 'attack2', Block: 'block', Summon: 'summon' }],
  'Skeleton Archer': ['skeleton_archer', { Summon: 'summon' }],
  'Armored Skeleton': ['skeleton_armored', { Attack02: 'attack2', Summon: 'summon' }],
  'Greatsword Skeleton': ['skeleton_great', { Attack02: 'attack2', Attack03: 'attack3', Summon: 'summon' }],
  'Slime': ['slime', { Attack02: 'attack2' }],
  'Werebear': ['werebear', { Attack02: 'attack2', Attack03: 'attack3' }],
  'Werewolf': ['werewolf', { Attack02: 'attack2' }],
  'Necromancer': ['necromancer', { Summon: 'summon' }],
  // a new enemy of the pack
  'Orc rider': ['orc_rider', { Idle: 'idle', Walk: 'walk', Attack01: 'attack1', Attack02: 'attack2', Attack03: 'attack3', Block: 'block', Hurt: 'hurt', Death: 'death' }]
};
// spell effects and the archers' arrow
const EXTRAS = [
  ['necro_summon_fx', 'Necromancer/Magic(projectile)/Necromancer_Sumon_Effect.png'],
  ['priest_heal_fx', 'Priest/Magic(projectile)/Priest_Heal_effect.png'],
  ['priest_attack_fx', 'Priest/Magic(projectile)/Priest_Attack_effect.png'],
  ['g_arrow', 'Archer/Arrow(projectile)/Arrow02(100x100).png']
];
// Minifolks villagers the game did not have yet (32x32 cells; rows read by registerNPCAnimations)
const VILLAGERS = { npc11: 'MiniNobleMan', npc12: 'MiniPeasant', npc13: 'MiniVillagerMan', npc14: 'MiniVillagerWoman' };

const out = {}, frames = {}, missing = [];
const add = (key, file, size, optional) => {
  if (!fs.existsSync(file)) { if (!optional) missing.push(path.relative(ROOT, file)); return; }
  out[key] = 'data:image/png;base64,' + fs.readFileSync(file).toString('base64');
  const r = framesPerRow(file, size);
  frames[key] = size === 100 ? r.frames[0] : r.frames;
};
Object.entries(CHARS).forEach(([folder, [id, anims]]) => {
  const dir = path.join(PACK, folder, folder + ' with shadows');
  Object.entries(anims).forEach(([src, anim]) => add(id + '_' + anim, path.join(dir, folder + '_' + src.replace('?', '') + '.png'), 100, src.endsWith('?')));
});
EXTRAS.forEach(([key, rel]) => add(key, path.join(PACK, rel), 100));
Object.entries(VILLAGERS).forEach(([id, file]) => add(id + '_villager', path.join(NPC, file + '.png'), 32));

if (missing.length) { console.error('Faltan en el pack:\n  ' + missing.join('\n  ')); process.exit(1); }
const lines = [
  '/* GENERATED by tools/pack/pack_extra.js - the rest of the character pack (guards\' attacks, enemies\' extra attacks,',
  '   blocks and summons, the orc rider, spell effects and four more villagers) embedded as data URIs. */',
  'window.GAME_ASSETS_BASE64 = window.GAME_ASSETS_BASE64 || {};',
  '/** Frames of each sheet: a number for the 100x100 sheets (one row), the frames of each row for the 32x32 villagers. */',
  'window.CK_ANIMS_EXTRA = ' + JSON.stringify(frames) + ';'
];
Object.entries(out).forEach(([k, v]) => lines.push("window.GAME_ASSETS_BASE64." + k + " = '" + v + "';"));
fs.writeFileSync(path.join(ROOT, 'js/chars_extra_assets.js'), lines.join('\n') + '\n');
console.log(Object.keys(out).length + ' hojas -> js/chars_extra_assets.js (' + Math.round(fs.statSync(path.join(ROOT, 'js/chars_extra_assets.js')).size / 1024) + ' KB)');
