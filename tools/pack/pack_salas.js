#!/usr/bin/env node
'use strict';
/* Junta las salas integradas con tools/pack/integrar_sala.js (archivos assets/fuentes/salas/sala_<mapa>.json, que quedan
   solo en la PC) en js/maps/data/salas_castillo_assets.js, que es lo que carga el juego (window.CK_SALAS_ARTE).
   Run:  node tools/pack/pack_salas.js     (or: npm run build:salas) */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..'), DIR = path.join(ROOT, 'assets/fuentes/salas');
const salas = {};
fs.readdirSync(DIR).filter(f => /^sala_.+\.json$/.test(f)).sort().forEach(f => {
  const s = JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8'));
  salas[s.mapa] = { base: s.base, suelo: s.suelo, piezas: s.piezas, capas: s.capas };
});
if (!Object.keys(salas).length) { console.error('No hay salas integradas en ' + path.relative(ROOT, DIR)); process.exit(1); }
const out = [
  '/* GENERATED by tools/pack/pack_salas.js - salas del castillo integradas desde su imagen original: piso completo (con los',
  '   muebles) y cada mueble recortado del mismo original en su lugar exacto, más las capas delanteras (barandas).',
  '   Lo aplica js/core/ck_salas_castillo.js solo si el mapa del editor sigue siendo el mismo (base). */',
  'window.CK_SALAS_ARTE = ' + JSON.stringify(salas) + ';'
].join('\n') + '\n';
fs.writeFileSync(path.join(ROOT, 'js/maps/data/salas_castillo_assets.js'), out);
console.log(Object.keys(salas).join(', ') + ' -> js/maps/data/salas_castillo_assets.js (' + Math.round(out.length / 1024) + ' KB)');
